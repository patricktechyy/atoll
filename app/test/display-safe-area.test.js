const assert = require('node:assert/strict');
const { capabilities } = require('../src/platform');
const { displayCutout } = require('../src/display-safe-area');
const mac = capabilities('darwin'), win = capabilities('win32');
const laptop = { id: 1, internal: true, bounds: { y: -982, width: 1512 }, workArea: { y: -944 }, scaleFactor: 2 };
const external = { id: 2, internal: false, bounds: { y: 0, width: 1920 }, workArea: { y: 25 } };
const camera = { x: 650, y: 0, width: 212, height: 38 };
const areas = () => [{ id: 2, top: 0, left: 0, width: 0 }, { id: 1, top: 38, left: 650, width: 212 }];
assert.deepEqual(displayCutout(laptop, mac, areas), camera, 'native DIPs, not Retina pixels or global y');
assert.equal(displayCutout(external, mac, areas), null, 'selected external screen has no camera');
assert.deepEqual(displayCutout({ ...laptop, id: '1' }, mac, areas), camera);
assert.equal(displayCutout(laptop, mac, () => [{ id: 1, top: 0 }]), null, 'notch-free laptops keep their layout');
const unavailable = () => { throw new Error('native module unavailable'); };
const fallback = { x: 0, y: 0, width: 1512, height: 38 };
assert.deepEqual(displayCutout(laptop, mac, unavailable), fallback, 'without camera width, reserve all of the top row');
assert.equal(displayCutout(external, mac, unavailable), null);
assert.deepEqual(displayCutout(laptop, mac, () => []), fallback, 'hot-plug race uses conservative fallback');
assert.deepEqual(displayCutout(laptop, mac, () => [{ id: 1, top: NaN }]), fallback);
assert.deepEqual(displayCutout(laptop, mac, () => [{ id: 1, top: 38, left: -1, width: 212 }]), fallback);
assert.equal(displayCutout({ ...laptop, workArea: undefined }, mac, unavailable), null);
assert.equal(displayCutout(laptop, win, () => { assert.fail('Windows must not load AppKit'); }), null);
console.log('Display cutout: per-display camera rectangle, DIPs, notch-free screens and safe fallback passed.');
